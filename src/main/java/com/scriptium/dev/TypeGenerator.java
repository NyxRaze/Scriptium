        private static ClassReader readClasspathClass(
                        String className) throws IOException {

                String resourceName = className.replace(
                                '.',
                                '/') + ".class";

                ClassLoader loader = TypeGenerator.class.getClassLoader();

                InputStream stream = loader.getResourceAsStream(
                                resourceName);

                if (stream == null) {

                        throw new IOException(
                                        "Class not found on classpath: "
                                                        + className);
                }

                try (stream) {

                        return new ClassReader(
                                        stream);
                }
        }

        private static ClassReader readClass(
                        Path minecraftJar,
                        String className) throws IOException {

                String entryName = className.replace(
                                '.',
                                '/') + ".class";

                try (JarFile jar = new JarFile(
                                minecraftJar.toFile())) {

                        JarEntry entry = jar.getJarEntry(
                                        entryName);

                        if (entry == null) {

                                throw new IOException(
                                                "Class not found in Minecraft JAR: "
                                                                + className);
                        }

                        try (InputStream stream = jar.getInputStream(entry)) {

                                return new ClassReader(
                                                stream);
                        }
                }
        }

        private static int getClassAccess(
                        ClassReader reader) {

                final int[] access = new int[1];

                reader.accept(
                                new ClassVisitor(Opcodes.ASM9) {

                                        @Override
                                        public void visit(
                                                        int version,
                                                        int accessFlags,
                                                        String name,
                                                        String signature,
                                                        String superName,
                                                        String[] interfaces) {

                                                access[0] = accessFlags;
                                        }
                                },
                                ClassReader.SKIP_CODE
                                                | ClassReader.SKIP_DEBUG
                                                | ClassReader.SKIP_FRAMES);

                return access[0];
        }

        private static boolean isUsable(
                        int access) {

                if ((access
                                & Opcodes.ACC_SYNTHETIC) != 0) {

                        return false;
                }

                if ((access
                                & Opcodes.ACC_BRIDGE) != 0) {

                        return false;
                }

                return (access
                                & Opcodes.ACC_PUBLIC) != 0
                                || (access
                                                & Opcodes.ACC_PROTECTED) != 0;
        }

        // ============================================================
        // Name sanitizing
        // ============================================================

        private static String sanitizeName(
                        String name) {

                return switch (name) {

                        case "constructor",
                                        "delete",
                                        "default",
                                        "new",
                                        "class",
                                        "function",
                                        "var",
                                        "let",
                                        "const",
                                        "return",
                                        "switch",
                                        "case",
                                        "break",
                                        "continue",
                                        "throw",
                                        "try",
                                        "catch",
                                        "finally" ->

                                "_" + name;

                        default ->
                                name;
                };
        }

        private static String sanitizeClassName(
                        String name) {

                String sanitized = name.replace(
                                '$',
                                '_');

                if (sanitized.isEmpty()) {
                        return "_";
                }

                char first = sanitized.charAt(0);

                if (!Character.isJavaIdentifierStart(
                                first)) {

                        sanitized = "_" + sanitized;
                }

                StringBuilder result = new StringBuilder();

                for (int i = 0; i < sanitized.length(); i++) {

                        char c = sanitized.charAt(i);

                        if (Character.isJavaIdentifierPart(c)) {

                                result.append(c);

                        } else {

                                result.append('_');
                        }
                }

                return result.toString();
        }

        private static boolean isAnonymousClass(
                        String className) {

                int dollar = className.lastIndexOf('$');

                if (dollar == -1) {
                        return false;
                }

                if (dollar + 1 >= className.length()) {
                        return false;
                }

                String suffix = className.substring(
                                dollar + 1);

                return suffix.chars()
                                .allMatch(
                                                Character::isDigit);
        }
