        private static Path findMinecraftJar()
                        throws IOException {

                String classPath = System.getProperty("java.class.path");

                String[] entries = classPath.split(
                                System.getProperty(
                                                "path.separator"));

                for (String entry : entries) {

                        Path path = Paths.get(entry);

                        if (!Files.isRegularFile(path)) {
                                continue;
                        }

                        if (!entry.endsWith(".jar")) {
                                continue;
                        }

                        try (JarFile jar = new JarFile(path.toFile())) {

                                JarEntry minecraftClass = jar.getJarEntry(
                                                "net/minecraft/client/Minecraft.class");

                                if (minecraftClass != null) {
                                        return path;
                                }
                        }
                }

                throw new IOException(
                                "Could not locate the Minecraft JAR."
                                                + " Make sure generateScriptTypes"
                                                + " uses sourceSets.main.runtimeClasspath.");
        }

        private static Set<String> findMinecraftClasses(
                        Path minecraftJar) throws IOException {

                Set<String> classes = new LinkedHashSet<>();

                try (JarFile jar = new JarFile(minecraftJar.toFile())) {

                        jar.stream()
                                        .filter(entry -> !entry.isDirectory())
                                        .filter(entry -> entry.getName().endsWith(".class"))
                                        .filter(entry -> entry.getName().startsWith(
                                                        "net/minecraft/")
                                                        || entry.getName().startsWith(
                                                                        "com/mojang/"))
                                        .filter(entry -> !entry.getName().equals(
                                                        "module-info.class"))
                                        .filter(entry -> !entry.getName().endsWith(
                                                        "/module-info.class"))
                                        .filter(entry -> !entry.getName().equals(
                                                        "package-info.class"))
                                        .filter(entry -> !entry.getName().endsWith(
                                                        "/package-info.class"))
                                        .forEach(entry -> {

                                                String name = entry.getName()
                                                                .substring(
                                                                                0,
                                                                                entry.getName()
                                                                                                .length() - 6)
                                                                .replace(
                                                                                '/',
                                                                                '.');

                                                if (name.contains(
                                                                "package-info")) {
                                                        return;
                                                }

                                                if (name.contains(
                                                                "module-info")) {
                                                        return;
                                                }

                                                if (isAnonymousClass(name)) {
                                                        return;
                                                }

                                                classes.add(name);
                                        });
                }

                return classes;
        }

