        private static void generateClass(
                        ClassReader reader,
                        String className,
                        StringBuilder result) {

                int access = getClassAccess(reader);

                String simpleName = getSimpleName(className);

                String packageName = getPackageName(className);

                if (simpleName.equals("package-info")) {
                        return;
                }

                if (simpleName.equals("module-info")) {
                        return;
                }

                appendNamespaceOpenings(
                                result,
                                packageName);

                int indent = namespaceDepth(packageName);

                appendIndent(
                                result,
                                indent);

                if ((access & Opcodes.ACC_ANNOTATION) != 0) {

                        result.append(
                                        "export interface ");

                } else if ((access & Opcodes.ACC_INTERFACE) != 0) {

                        result.append(
                                        "export interface ");

                } else {

                        result.append(
                                        "export class ");
                }

                result.append(
                                sanitizeClassName(simpleName));

                String superName = reader.getSuperName();

                if (superName != null
                                && !superName.equals(
                                                "java/lang/Object")
                                && !superName.equals(
                                                "java/lang/Enum")) {

                        String parent = superName.replace(
                                        '/',
                                        '.');

                        /*
                         * Minecraft and Scriptium classes can both be
                         * referenced from the generated typings.
                         */
                        if (parent.startsWith(
                                        MINECRAFT_PACKAGE)
                                        || parent.startsWith(
                                                        SCRIPTIUM_PACKAGE)) {

                                result.append(
                                                " extends ");

                                result.append(
                                                typeName(parent));
                        }
                }

                result.append(
                                " {\n\n");

                generateMembers(
                                reader,
                                result,
                                indent + 1);

                appendIndent(
                                result,
                                indent);

                result.append(
                                "}\n");

                appendNamespaceClosings(
                                result,
                                packageName);

                result.append(
                                "\n");
        }

