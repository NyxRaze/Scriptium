        private static void generateGuiScriptTypes(StringBuilder result)
                        throws IOException {

                Path sourcePath = Paths.get(
                                "src", "main", "java",
                                "com", "scriptium", "scripting", "api", "GuiAPI.java");

                if (!Files.isRegularFile(sourcePath)) {
                        throw new IOException(
                                        "Cannot find GuiAPI.java at " + sourcePath.toAbsolutePath());
                }

                String source = Files.readString(sourcePath);

                result.append("""
                                // Script-facing GUI types inferred from GuiAPI.java.

                                interface ScriptiumGuiAPI {
                                    create(options?: GuiCreateOptions): ScriptiumGuiScreen;
                                }

                                interface ScriptiumGuiScreen {
                                    tab(options: string | GuiScreenTabOptions): ScriptiumGuiScreen;
                                    label(options: GuiScreenLabelOptions): ScriptiumGuiScreen;
                                    heading(options: GuiScreenHeadingOptions): ScriptiumGuiScreen;
                                    button(options: GuiScreenButtonOptions): ScriptiumGuiScreen;
                                    toggle(options: GuiScreenToggleOptions): ScriptiumGuiScreen;
                                    card(options: GuiScreenCardOptions): ScriptiumGuiScreen;
                                    slider(options: GuiScreenSliderOptions): ScriptiumGuiScreen;
                                    separator(options?: GuiScreenSeparatorOptions): ScriptiumGuiScreen;
                                    spacer(size?: number | GuiScreenSpacerOptions): ScriptiumGuiScreen;
                                    setValue(id: string, value: boolean | number | string | number[]): ScriptiumGuiScreen;
                                    getValue(id: string): boolean | number | string | number[];
                                    getRandomValue(id: string): number;
                                    open(): void;
                                    close(): void;
                                }

                                interface ScriptiumGuiSettingsPanel {
                                    heading(options: GuiSettingsPanelHeadingOptions): ScriptiumGuiSettingsPanel;
                                    label(options: GuiSettingsPanelLabelOptions): ScriptiumGuiSettingsPanel;
                                    toggle(options: GuiSettingsPanelToggleOptions): ScriptiumGuiSettingsPanel;
                                    slider(options: GuiSettingsPanelSliderOptions): ScriptiumGuiSettingsPanel;
                                    range(options: GuiSettingsPanelRangeOptions): ScriptiumGuiSettingsPanel;
                                    enumeration(options: GuiSettingsPanelEnumerationOptions): ScriptiumGuiSettingsPanel;
                                    keybind(options: GuiSettingsPanelKeybindOptions): ScriptiumGuiSettingsPanel;
                                    button(options: GuiSettingsPanelButtonOptions): ScriptiumGuiSettingsPanel;
                                    separator(options?: GuiSettingsPanelSeparatorOptions): ScriptiumGuiSettingsPanel;
                                    spacer(size?: number | GuiSettingsPanelSpacerOptions): ScriptiumGuiSettingsPanel;
                                }

                                """);

                /*
                 * Find public methods that accept a Graal Value named "options".
                 * The containing class name distinguishes GuiAPI, GuiScreen and
                 * SettingsPanel methods that share names such as "label" and "toggle".
                 */
                Pattern methodPattern = Pattern.compile(
                                "\\bpublic\\s+(?:static\\s+)?[\\w.$<>?,\\s]+?\\s+" +
                                                "(\\w+)\\s*\\(\\s*Value\\s+(\\w+)\\s*\\)\\s*\\{");

                Matcher matcher = methodPattern.matcher(source);

                while (matcher.find()) {
                        String methodName = matcher.group(1);
                        String parameterName = matcher.group(2);

                        int bodyStart = matcher.end() - 1;
                        int bodyEnd = findMatchingBrace(source, bodyStart);

                        if (bodyEnd < 0) {
                                continue;
                        }

                        String body = source.substring(bodyStart + 1, bodyEnd);

                        String owner = findEnclosingGuiClass(source, matcher.start());

                        if (owner == null) {
                                continue;
                        }

                        String interfaceName = switch (owner) {
                                case "GuiAPI" -> "Gui" + capitalize(methodName) + "Options";
                                case "GuiScreen" -> "GuiScreen" + capitalize(methodName) + "Options";
                                case "SettingsPanel" ->
                                        "GuiSettingsPanel" + capitalize(methodName) + "Options";
                                default -> "Gui" + owner + capitalize(methodName) + "Options";
                        };

                        Map<String, String> properties = new LinkedHashMap<>();

                        inferOptionProperties(body, parameterName, properties);

                        if ("SettingsPanel".equals(owner)) {
                                properties.putIfAbsent("id", "string");
                        }

                        if ("SettingsPanel".equals(owner) && "enumeration".equals(methodName)) {
                                properties.put("options", "string[]");
                                properties.put("value", "string");
                                properties.put("onChange", "(value: string) => void");
                        } else if ("SettingsPanel".equals(owner) && "keybind".equals(methodName)) {
                                properties.put("value", "number");
                                properties.put("onChange", "(newKeyCode: number) => void");
                        } else if ("SettingsPanel".equals(owner) && "range".equals(methodName)) {
                                properties.put("value", "[number, number]");
                                properties.put("onChange", "(low: number, high: number) => void");
                        }

                        if (properties.isEmpty()) {
                                continue;
                        }

                        result.append("interface ")
                                        .append(interfaceName)
                                        .append(" {\n");

                        for (Map.Entry<String, String> property : properties.entrySet()) {
                                result.append("    ")
                                                .append(property.getKey())
                                                .append("?: ")
                                                .append(property.getValue())
                                                .append(";\n");
                        }

                        result.append("}\n\n");
                }
        }

        private static void inferOptionProperties(
                        String body,
                        String optionsVariable,
                        Map<String, String> properties) {

                String variable = Pattern.quote(optionsVariable);

                // Properties read through option helpers.
                inferHelperProperties(body, variable, "getString", "string", properties);
                inferHelperProperties(body, variable, "getInt", "number", properties);
                inferHelperProperties(body, variable, "getDouble", "number", properties);
                inferHelperProperties(body, variable, "getBoolean", "boolean", properties);
                inferHelperProperties(body, variable, "getColor", "string | number", properties);

                Pattern callbackPattern = Pattern.compile(
                                "\\bgetCallback\\s*\\(\\s*" + variable
                                                + "\\s*,\\s*\"([^\"]+)\"\\s*\\)");
                Matcher callbacks = callbackPattern.matcher(body);

                while (callbacks.find()) {
                        properties.putIfAbsent(callbacks.group(1), "() => boolean");
                }

                // Properties read using member(options, "key").
                Pattern helperMemberPattern = Pattern.compile(
                                "\\bmember\\s*\\(\\s*" + variable
                                                + "\\s*,\\s*\"([^\"]+)\"\\s*\\)");

                Matcher helperMembers = helperMemberPattern.matcher(body);

                while (helperMembers.find()) {
                        String name = helperMembers.group(1);

                        String type = switch (name) {
                                case "onClick" -> "() => void";
                                case "onChange" -> "(value: any) => void";
                                case "visibleWhen" -> "() => boolean";
                                case "settings" ->
                                        "(panel: ScriptiumGuiSettingsPanel) => void";
                                case "value" -> "boolean";
                                default -> "unknown";
                        };

                        properties.putIfAbsent(name, type);
                }

                // Properties read directly using options.getMember("key").
                Pattern memberPattern = Pattern.compile(
                                variable + "\\s*\\.\\s*getMember\\s*\\(\\s*\"([^\"]+)\"\\s*\\)");

                Matcher members = memberPattern.matcher(body);

                while (members.find()) {
                        String name = members.group(1);
                        properties.putIfAbsent(name, getOptionPropertyType(name));
                }

                // card() selects a callback conditionally, so the property names
                // cannot both be discovered by the direct-member regex.
                if (body.contains("\"onChange\"")
                                && body.contains("\"onClick\"")) {
                        properties.put("onChange", "(value: any) => void");
                        properties.put("onClick", "() => void");
                }
        }

        private static String getOptionPropertyType(String name) {
                return switch (name) {
                        case "onClick" -> "() => void";
                        case "onChange" -> "(value: any) => void";
                        case "settings" ->
                                "(panel: ScriptiumGuiSettingsPanel) => void";

                        case "min", "max", "step", "value",
                                        "width", "height", "columns",
                                        "padding", "gap", "size" ->
                                "number";

                        case "inline", "required", "disabled" -> "boolean";

                        case "id", "title", "subtitle", "footer", "text",
                                        "description", "name", "icon", "variant" ->
                                "string";

                        default -> "unknown";
                };
        }

        private static void inferHelperProperties(
                        String body,
                        String variable,
                        String helper,
                        String type,
                        Map<String, String> properties) {

                Pattern pattern = Pattern.compile(
                                "\\b" + Pattern.quote(helper) +
                                                "\\s*\\(\\s*" + variable +
                                                "\\s*,\\s*\"([^\"]+)\"");

                Matcher matcher = pattern.matcher(body);

                while (matcher.find()) {
                        properties.putIfAbsent(matcher.group(1), type);
                }
        }

        private static int findMatchingBrace(String source, int openingBrace) {
                int depth = 0;
                boolean inString = false;
                boolean inChar = false;
                boolean escaped = false;

                for (int i = openingBrace; i < source.length(); i++) {
                        char c = source.charAt(i);

                        if (escaped) {
                                escaped = false;
                                continue;
                        }

                        if ((inString || inChar) && c == '\\') {
                                escaped = true;
                                continue;
                        }

                        if (!inChar && c == '"') {
                                inString = !inString;
                                continue;
                        }

                        if (!inString && c == '\'') {
                                inChar = !inChar;
                                continue;
                        }

                        if (inString || inChar) {
                                continue;
                        }

                        if (c == '{') {
                                depth++;
                        } else if (c == '}' && --depth == 0) {
                                return i;
                        }
                }

                return -1;
        }

        private static String findEnclosingGuiClass(String source, int position) {
                Pattern classPattern = Pattern.compile(
                                "\\bclass\\s+(GuiScreen|SettingsPanel|GuiAPI)\\b");

                Matcher matcher = classPattern.matcher(source);

                String owner = null;

                while (matcher.find() && matcher.start() < position) {
                        owner = matcher.group(1);
                }

                return owner;
        }

        private static String capitalize(String value) {
                if (value == null || value.isEmpty()) {
                        return value;
                }

                return Character.toUpperCase(value.charAt(0)) + value.substring(1);
        }

