        // ============================================================
        // Members
        // ============================================================

        private static void generateMembers(
                        ClassReader reader,
                        StringBuilder result,
                        int indent) {

                Set<String> methods = new LinkedHashSet<>();

                reader.accept(
                                new ClassVisitor(Opcodes.ASM9) {

                                        @Override
                                        public FieldVisitor visitField(
                                                        int access,
                                                        String name,
                                                        String descriptor,
                                                        String signature,
                                                        Object value) {

                                                if (!isUsable(access)) {
                                                        return null;
                                                }

                                                appendIndent(
                                                                result,
                                                                indent);

                                                if ((access
                                                                & Opcodes.ACC_STATIC) != 0) {

                                                        result.append(
                                                                        "static ");
                                                }

                                                result.append(
                                                                sanitizeName(name));

                                                result.append(
                                                                ": ");

                                                result.append(
                                                                toType(
                                                                                Type.getType(
                                                                                                descriptor)));

                                                result.append(
                                                                ";\n");

                                                return null;
                                        }

                                        @Override
                                        public MethodVisitor visitMethod(
                                                        int access,
                                                        String name,
                                                        String descriptor,
                                                        String signature,
                                                        String[] exceptions) {

                                                if (!isUsable(access)) {
                                                        return null;
                                                }

                                                if (name.equals("<clinit>")) {
                                                        return null;
                                                }

                                                if (name.equals("<init>")) {

                                                        generateConstructor(
                                                                        result,
                                                                        descriptor,
                                                                        indent);

                                                        return null;
                                                }

                                                String key = name + descriptor;

                                                if (!methods.add(key)) {
                                                        return null;
                                                }

                                                generateMethod(
                                                                result,
                                                                name,
                                                                descriptor,
                                                                access,
                                                                indent);

                                                return null;
                                        }
                                },
                                ClassReader.SKIP_DEBUG);
        }

        private static void generateConstructor(
                        StringBuilder result,
                        String descriptor,
                        int indent) {

                Type method = Type.getMethodType(
                                descriptor);

                Type[] arguments = method.getArgumentTypes();

                appendIndent(
                                result,
                                indent);

                result.append(
                                "constructor(");

                for (int i = 0; i < arguments.length; i++) {

                        if (i > 0) {
                                result.append(", ");
                        }

                        result.append("arg");
                        result.append(i);
                        result.append(": ");

                        result.append(
                                        toType(arguments[i]));
                }

                result.append(
                                ");\n");
        }

        private static void generateMethod(
                        StringBuilder result,
                        String name,
                        String descriptor,
                        int access,
                        int indent) {

                Type method = Type.getMethodType(
                                descriptor);

                Type[] arguments = method.getArgumentTypes();

                appendIndent(
                                result,
                                indent);

                if ((access
                                & Opcodes.ACC_STATIC) != 0) {

                        result.append(
                                        "static ");
                }

                result.append(
                                sanitizeName(name));

                result.append(
                                "(");

                for (int i = 0; i < arguments.length; i++) {

                        if (i > 0) {
                                result.append(", ");
                        }

                        result.append("arg");
                        result.append(i);
                        result.append(": ");

                        result.append(
                                        toType(arguments[i]));
                }

                result.append(
                                "): ");

                result.append(
                                toType(
                                                method.getReturnType()));

                result.append(
                                ";\n");
        }

        // ============================================================
        // Type conversion
        // ============================================================

        private static String toType(
                        Type type) {

                return switch (type.getSort()) {

                        case Type.VOID ->
                                "void";

                        case Type.BOOLEAN ->
                                "boolean";

                        case Type.BYTE,
                                        Type.SHORT,
                                        Type.CHAR,
                                        Type.INT,
                                        Type.LONG,
                                        Type.FLOAT,
                                        Type.DOUBLE ->
                                "number";

                        case Type.ARRAY -> {

                                String element = toType(
                                                type.getElementType());

                                yield element + "[]";
                        }

                        case Type.OBJECT -> {

                                String name = type.getClassName();

                                yield mapJavaType(name);
                        }

                        default ->
                                "any";
                };
        }

        private static String mapJavaType(
                        String name) {

                if (name.equals(
                                "java.lang.String")) {
                        return "string";
                }

                if (name.equals(
                                "java.lang.Boolean")) {
                        return "boolean";
                }

                if (name.equals(
                                "java.lang.Number")) {
                        return "number";
                }

                if (name.equals(
                                "java.lang.Integer")
                                || name.equals(
                                                "java.lang.Long")
                                || name.equals(
                                                "java.lang.Double")
                                || name.equals(
                                                "java.lang.Float")
                                || name.equals(
                                                "java.lang.Short")
                                || name.equals(
                                                "java.lang.Byte")) {

                        return "number";
                }

                if (name.equals(
                                "java.lang.Object")) {
                        return "any";
                }

                if (name.equals(
                                "java.util.List")
                                || name.equals(
                                                "java.util.Collection")) {

                        return "JavaList<any>";
                }

                if (name.equals(
                                "java.util.Set")) {

                        return "JavaSet<any>";
                }

                if (name.equals(
                                "java.util.Map")) {

                        return "JavaMap<any, any>";
                }

                if (name.equals(
                                "java.util.Optional")) {

                        return "any";
                }

                if (name.startsWith(
                                MINECRAFT_PACKAGE)) {

                        return typeName(name);
                }

                if (name.startsWith(
                                MOJANG_PACKAGE)) {

                        return typeName(name);
                }

                if (name.startsWith(
                                SCRIPTIUM_PACKAGE)) {

                        return typeName(name);
                }

                return "any";
        }

        // ============================================================
        // TypeScript namespaces
        // ============================================================

        private static String typeName(
                        String className) {

                String normalized = className.replace(
                                '$',
                                '.');

                String[] parts = normalized.split(
                                "\\.");

                StringBuilder result = new StringBuilder();

                for (int i = 0; i < parts.length; i++) {

                        if (i > 0) {
                                result.append(".");
                        }

                        result.append(
                                        sanitizeClassName(
                                                        parts[i]));
                }

                return result.toString();
        }

        private static String getPackageName(
                        String className) {

                int index = className.lastIndexOf('.');

                if (index == -1) {
                        return "";
                }

                return className.substring(
                                0,
                                index);
        }

        private static String getSimpleName(
                        String className) {

                int index = className.lastIndexOf('.');

                if (index == -1) {
                        return className;
                }

                return className.substring(
                                index + 1);
        }

        private static int namespaceDepth(
                        String packageName) {

                if (packageName.isEmpty()) {
                        return 0;
                }

                return packageName.split(
                                "\\.").length;
        }

        private static void appendNamespaceOpenings(
                        StringBuilder result,
                        String packageName) {

                if (packageName.isEmpty()) {
                        return;
                }

                String[] parts = packageName.split(
                                "\\.");

                int indent = 0;

                for (String part : parts) {

                        appendIndent(
                                        result,
                                        indent);

                        result.append(
                                        "declare namespace ");

                        result.append(
                                        sanitizeClassName(part));

                        result.append(
                                        " {\n");

                        indent++;
                }
        }

        private static void appendNamespaceClosings(
                        StringBuilder result,
                        String packageName) {

                int depth = namespaceDepth(packageName);

                for (int i = depth - 1; i >= 0; i--) {

                        appendIndent(
                                        result,
                                        i);

                        result.append(
                                        "}\n");
                }
        }

        private static void appendIndent(
                        StringBuilder result,
                        int amount) {

                result.append(
                                "    ".repeat(amount));
        }

