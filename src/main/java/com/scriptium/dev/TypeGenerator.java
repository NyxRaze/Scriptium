        private static Set<String> findScriptiumClasses()
                        throws IOException {

                Set<String> classes = new LinkedHashSet<>();

                String classPath = System.getProperty("java.class.path");

                String[] entries = classPath.split(
                                System.getProperty(
                                                "path.separator"));

                for (String entry : entries) {

                        Path path = Paths.get(entry);

                        if (Files.isDirectory(path)) {

                                Path packagePath = path.resolve(
                                                "com/scriptium/scripting");

                                if (!Files.isDirectory(packagePath)) {
                                        continue;
                                }

                                try (var stream = Files.walk(packagePath)) {

                                        stream
                                                        .filter(Files::isRegularFile)
                                                        .filter(file -> file.toString()
                                                                        .endsWith(
                                                                                        ".class"))
                                                        .forEach(file -> {

                                                                String relative = path.relativize(
                                                                                file).toString();

                                                                String className = relative
                                                                                .substring(
                                                                                                0,
                                                                                                relative.length() - 6)
                                                                                .replace(
                                                                                                '/',
                                                                                                '.')
                                                                                .replace(
                                                                                                '\\',
                                                                                                '.');

                                                                addScriptiumClass(
                                                                                classes,
                                                                                className);
                                                        });
                                }

                        } else if (Files.isRegularFile(path)
                                        && entry.endsWith(".jar")) {

                                try (JarFile jar = new JarFile(path.toFile())) {

                                        jar.stream()
                                                        .filter(entry2 -> !entry2.isDirectory())
                                                        .filter(entry2 -> entry2.getName()
                                                                        .endsWith(
                                                                                        ".class"))
                                                        .filter(entry2 -> entry2.getName()
                                                                        .startsWith(
                                                                                        "com/scriptium/scripting/"))
                                                        .forEach(entry2 -> {

                                                                String className = entry2.getName()
                                                                                .substring(
                                                                                                0,
                                                                                                entry2.getName()
                                                                                                                .length()
                                                                                                                - 6)
                                                                                .replace(
                                                                                                '/',
                                                                                                '.');

                                                                addScriptiumClass(
                                                                                classes,
                                                                                className);
                                                        });
                                }
                        }
                }

                return classes;
        }

        private static void addScriptiumClass(
                        Set<String> classes,
                        String className) {

                if (className.contains(
                                "package-info")) {
                        return;
                }

                if (className.contains(
                                "module-info")) {
                        return;
                }

                if (isAnonymousClass(className)) {
                        return;
                }

                /*
                 * Only expose actual scripting API packages.
                 *
                 * Implementation classes such as ScriptManager,
                 * EventManager and KeybindManager are intentionally
                 * not exposed to JavaScript typings.
                 */
                if (!className.startsWith(
                                "com.scriptium.scripting.api.")
                                && !className.startsWith(
                                                "com.scriptium.scripting.event.")
                                && !className.startsWith(
                                                "com.scriptium.scripting.keybind.")) {
                        return;
                }

                classes.add(className);
        }

